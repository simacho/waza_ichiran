function determineNormalizedGripCategory(rawGrip: string): string {
  const clean = rawGrip.replace('※', '').trim();
  if (clean.includes('後ろ技')) return '後ろ技';
  if (clean.includes('半身半立ち')) return '半身半立ち';
  if (clean.includes('短刀') || clean.includes('剣') || clean.includes('人取り')) return '武器・多人数';
  return clean;
}

function determineGrade(rawGrip: string, name: string, isSuwari: boolean): Grade {
  const clean = rawGrip.replace('※', '').trim();

  if (clean === '正面打ち') {
    if (name.includes('四方投げ') || name.includes('一ヵ条')) return isSuwari ? '6・5級' : '7・8級';
    if (name.includes('二ヵ条') || name.includes('側面入身投げ')) return isSuwari ? '5級' : '6・5級';
    if (name.includes('三ヵ条') || name.includes('正面入身投げ')) return isSuwari ? '3級' : '4級';
    if (name.includes('四ヵ条') || name.includes('肘締め')) return isSuwari ? '2級' : '3級';
    if (name.includes('小手返し') || name.includes('肘当て呼吸投げ')) return isSuwari ? '1級' : '2級';
    return '1級';
  }

  if (clean === '横面打ち' || clean === '片手打ち' || clean === '両手持ち') {
    if (name.includes('四方投げ') || name.includes('一ヵ条')) return '6・5級';
    if (name.includes('二ヵ条') || name.includes('側面入身投げ')) return '4級';
    if (name.includes('三ヵ条') || name.includes('正面入身投げ')) return '3級';
    if (name.includes('四ヵ条') || name.includes('肘締め')) return '2級';
    return '1級';
  }

  if (clean.includes('後ろ技') || clean.includes('半身半立ち')) return '初段';
  if (clean.includes('短刀') || clean.includes('剣') || clean.includes('人取り')) return '二段';

  return '1級';
}

