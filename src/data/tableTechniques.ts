function assignGrade(grip: string, name: string, isSuwari: boolean): Grade {
  if (name.includes('四方投げ') || name.includes('一ヵ条')) {
    return isSuwari ? '6・5級' : '7・8級';
  }
  if (name.includes('二ヵ条') || name.includes('側面入身投げ')) {
    return isSuwari ? '4級' : '6・5級';
  }
  if (name.includes('三ヵ条') || name.includes('正面入身投げ')) {
    return isSuwari ? '3級' : '4級';
  }
  if (name.includes('四ヵ条') || name.includes('肘締め')) {
    return isSuwari ? '2級' : '3級';
  }
  if (name.includes('小手返し') || name.includes('肘当て呼吸投げ')) {
    return isSuwari ? '1級' : '2級';
  }
  if (grip.includes('後ろ技') || grip.includes('半身半立ち')) {
    return '初段';
  }
  if (grip.includes('短刀') || grip.includes('剣') || grip.includes('人取り')) {
    return '二段';
  }
  return '初段';
}

function assignDescription(grip: string, name: string, isSuwari: boolean): string {
  const stanceText = isSuwari ? '【座り技 (※)】' : '【立ち技】';
  return `${stanceText} ${grip}に対する${name}の基本動作および崩し技。中心軸を保ち、相手の体勢を崩して制します。`;
}

